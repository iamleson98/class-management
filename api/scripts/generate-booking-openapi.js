const fs = require("fs");
const path = require("path");

const bookingApiDir = path.resolve(__dirname, "..", "..", "server", "channels", "api4", "booking_api");
const outputFile = path.resolve(__dirname, "..", "v4", "source", "booking_api.yaml");

const methodOrder = ["get", "post", "put", "patch", "delete"];

function toOpenAPIPath(routePath) {
  const normalized = routePath.replace(/\{([^}:]+):[^}]+\}/g, "{$1}");
  return `/api/v4/booking${normalized}`;
}

function toOperationId(method, routePath) {
  const clean = routePath
    .replace(/\{([^}:]+):[^}]+\}/g, "$1")
    .split("/")
    .filter(Boolean)
    .map((part) =>
      part
        .split(/[^a-zA-Z0-9]+/)
        .filter(Boolean)
        .map((token) => token.charAt(0).toUpperCase() + token.slice(1))
        .join(""),
    )
    .join("");

  return `Booking${method.charAt(0).toUpperCase()}${method.slice(1)}${clean}`;
}

function getPathParams(routePath) {
  const params = [];
  const regex = /\{([^}:]+):[^}]+\}/g;
  let match = regex.exec(routePath);
  while (match) {
    params.push(match[1]);
    match = regex.exec(routePath);
  }
  return params;
}

function parseRoutes(content) {
  const routes = [];
  const lines = content.split(/\r?\n/);

  for (const line of lines) {
    const match = line.match(/api\.routes\.Handle\("([^"]+)"\s*,\s*.*\)\.Methods\(http\.Method([A-Za-z]+)\)/);
    if (!match) {
      continue;
    }

    routes.push({
      routePath: match[1],
      method: match[2].toLowerCase(),
    });
  }

  return routes;
}

function buildYaml(pathToMethods) {
  const lines = [
    "# This file is auto-generated by scripts/generate-booking-openapi.js.",
    "# Edit server/channels/api4/booking_api/*.go and regenerate instead of editing this file manually.",
  ];

  const sortedPaths = Array.from(pathToMethods.keys()).sort();

  for (const openapiPath of sortedPaths) {
    lines.push(`  ${openapiPath}:`);

    const methods = Array.from(pathToMethods.get(openapiPath)).sort(
      (a, b) => methodOrder.indexOf(a) - methodOrder.indexOf(b),
    );

    for (const method of methods) {
      lines.push(`    ${method}:`);
      lines.push("      tags:");
      lines.push("        - booking");
      lines.push(`      summary: Booking ${method.toUpperCase()} ${openapiPath}`);
      lines.push(`      operationId: ${toOperationId(method, openapiPath)}`);

      const params = getPathParams(openapiPath);
      if (params.length > 0) {
        lines.push("      parameters:");
        for (const name of params) {
          lines.push("        - in: path");
          lines.push(`          name: ${name}`);
          lines.push("          required: true");
          lines.push("          schema:");
          lines.push("            type: string");
        }
      }

      lines.push("      responses:");
      lines.push(`        \"${method === "post" ? "201" : "200"}\":`);
      lines.push("          description: Success.");
    }
  }

  return `${lines.join("\n")}\n`;
}

function main() {
  const files = fs.readdirSync(bookingApiDir).filter((name) => name.endsWith(".go"));
  const allRoutes = [];

  for (const fileName of files) {
    const filePath = path.join(bookingApiDir, fileName);
    const content = fs.readFileSync(filePath, "utf8");
    const routes = parseRoutes(content);
    allRoutes.push(...routes);
  }

  const deduped = new Map();
  for (const route of allRoutes) {
    const openapiPath = toOpenAPIPath(route.routePath);
    if (!deduped.has(openapiPath)) {
      deduped.set(openapiPath, new Set());
    }
    deduped.get(openapiPath).add(route.method);
  }

  const yaml = buildYaml(deduped);
  fs.writeFileSync(outputFile, yaml, "utf8");

  console.log(`Generated ${outputFile}`);
  console.log(`Paths: ${deduped.size}, operations: ${allRoutes.length}`);
}

main();
